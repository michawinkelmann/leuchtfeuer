import * as D from "./shared/data.js";
import { GATE_NAMES } from "./shared/board.js";
import { TERRAIN_EN, GATE_EN, RES_EN, FAME_EN, resEn, logEn } from "./shared/log_en.js";
import { SPRACHE, ergaenze } from "./sprache.js";

export const EN = SPRACHE === "en";
const gross = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : s);
const pl = (n, eins, mehr) => (Number(n) === 1 ? eins : mehr);

// ---------------------------------------------------------------- Namen
/** Gelände für Knöpfe, Listen, Titel: „Wald“ / „Forest“ */
export const gelaende = (k) => (EN ? gross(TERRAIN_EN[k]) : D.TERRAIN_NAME[k]);
/** Gelände im Satz: „Wald“ / „forest“ */
export const gelaendeSatz = (k) => (EN ? TERRAIN_EN[k] : D.TERRAIN_NAME[k]);
/** Würfelseite: Gelände oder Auge */
export const wuerfelName = (f) => (EN ? (f === "auge" ? "Eye" : gross(TERRAIN_EN[f])) : D.TERRAIN_NAME[f] || "Auge");
/** Rohstoff für Knöpfe und Bildtitel: „Holz“ / „Wood“ */
export const rohstoff = (r) => (EN ? gross(RES_EN[r]) : D.RES_NAME[r]);
/** Rohstoff im Satz, englisch mit Zahl („1 horse“): „Holz“ / „wood“ */
export const rohstoffSatz = (r, n) => (EN ? resEn(r, n) : D.RES_NAME[r]);
export const torName = (key) => (EN ? GATE_EN[key] : GATE_NAMES[key]);
/** Herkunft des Ruhms beim Spielende (Schlüssel von fameBy; deutsch wie bisher der Schlüssel selbst) */
export const ruhmGrund = (k) => (EN ? FAME_EN[k] || k : k);
/** Verlauf, Fehler und Spielende aus der Engine */
export const logText = (m) => (EN ? logEn(m) : m);
/** Name zu einem Bildzeichen (ui.icon) */
export function bildName(name) {
  if (!EN) return D.RES_NAME[name] || D.TERRAIN_NAME[name] || (name === "auge" ? "Auge" : name);
  return gross(RES_EN[name] || TERRAIN_EN[name]) || (name === "auge" ? "Eye" : name);
}

